def esc(v):
    v = escape(v).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if v.startswith("@") or v.startswith("?"): v = "\\" + v
    return v

def write(path, idx):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen_android_strings.py - edit the table there. -->\n<resources>\n')
        for k in sorted(S):
            attrs = ' translatable="false"' if k == "app_name" and idx == 0 else ''
            if k == "app_name" and idx == 1: continue
            f.write(f'    <string name="{k}"{attrs}>{esc(S[k][idx])}</string>\n')
        for k, v in PLURALS.items():
            f.write(f'    <plurals name="{k}">\n')
            for q, t in v[idx].items(): f.write(f'        <item quantity="{q}">{esc(t)}</item>\n')
            f.write('    </plurals>\n')
        f.write('</resources>\n')

